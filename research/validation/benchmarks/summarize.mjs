// Turns a run directory into summary.json and summary.md.
//
// Every figure is the MEDIAN across independent trials of that trial's own
// statistic, shown with the min–max range across trials and the coefficient of
// variation, so a reader sees how much the run moved, not just where it sat.
//
// Usage: node summarize.mjs <run-dir>

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { acrossTrials } from './lib/stats.mjs';

const f = (v, d = 3) => (Number.isFinite(v) ? v.toFixed(d) : 'n/a');
const range = (s, d = 3) => `${f(s.min, d)}–${f(s.max, d)}`;

export function summarize(runDir) {
  const env = JSON.parse(readFileSync(path.join(runDir, 'env.json'), 'utf8'));
  const out = { runDir: path.basename(runDir), env, verifyCost: [], http: [], preflights: [] };
  const md = [];

  md.push(`# Benchmark summary — ${path.basename(runDir)}`, '');
  md.push('> Generated by `summarize.mjs` from the raw files in this directory. Medians across independent trials;');
  md.push('> ranges are min–max across trials; CV is the coefficient of variation of the per-trial statistic.');
  md.push('> One machine, one session. Not a general performance claim — see METHODOLOGY.md.', '');
  md.push('## Environment', '');
  md.push(`- Commit: \`${env.git.commit}\` on \`${env.git.branch}\`; uncommitted paths at run time: ${env.git.dirty.length}`);
  md.push(`- Node ${env.runtime.node}, npm ${env.runtime.npm}, V8 ${env.runtime.v8}, OpenSSL ${env.runtime.openssl}`);
  md.push(`- OS: ${env.os.version ?? env.os.platform} (${env.os.release}, ${env.os.arch})${env.os.powerPlan ? `; ${env.os.powerPlan.replace(/^Power Scheme GUID: \S+\s*/, 'power plan ')}` : ''}`);
  md.push(`- CPU: ${env.cpu.model} — ${env.cpu.physicalCores ?? '?'} physical / ${env.cpu.logicalCores} logical cores`);
  md.push(`- RAM: ${(env.memory.totalBytes / 2 ** 30).toFixed(1)} GiB total, ${(env.memory.freeBytesAtStart / 2 ** 30).toFixed(1)} GiB free at start`);
  md.push(`- Redis ${env.redis.version} (${env.redis.os}); config ${JSON.stringify(env.redis.config)}`);
  md.push(`- Docker server ${env.docker.server}; containers running during the run: ${env.docker.runningContainers.length}`);
  md.push(`- Packages: ${Object.entries(env.packages).map(([k, v]) => `${k}@${v}`).join(', ')}`, '');

  const vcPath = path.join(runDir, 'verify-cost.trials.json');
  if (existsSync(vcPath)) {
    const { meta, rows } = JSON.parse(readFileSync(vcPath, 'utf8'));
    const ids = [...new Set(rows.map((r) => r.id))];
    md.push('## Comparison 1 — verification cost (in-process, concurrency 1)', '');
    md.push('| Operation | Group | Trials | p50 ms (range) | p95 ms | p99 ms | ops/s from mean (range) | CV of p50 |');
    md.push('|---|---|---|---|---|---|---|---|');
    for (const id of ids) {
      const rs = rows.filter((r) => r.id === id);
      const p50 = acrossTrials(rs.map((r) => r.p50Ms));
      const p95 = acrossTrials(rs.map((r) => r.p95Ms));
      const p99 = acrossTrials(rs.map((r) => r.p99Ms));
      const ops = acrossTrials(rs.map((r) => r.opsPerSec));
      out.verifyCost.push({ id, group: meta[id].group, checks: meta[id].checks, iterationsPerTrial: rs[0].iterations, p50, p95, p99, opsPerSec: ops });
      md.push(`| \`${id}\` | ${meta[id].group} | ${p50.n} | ${f(p50.median)} (${range(p50)}) | ${f(p95.median)} | ${f(p99.median)} | ${f(ops.median, 0)} (${range(ops, 0)}) | ${f(p50.cvPercent, 1)}% |`);
    }
    md.push('', '### What each operation checks', '');
    for (const id of ids) md.push(`- \`${id}\` — ${meta[id].checks}`);
    md.push('');
  }

  const httpPath = path.join(runDir, 'http.trials.json');
  if (existsSync(httpPath)) {
    const { checks, preflights, rows } = JSON.parse(readFileSync(httpPath, 'utf8'));
    out.preflights = preflights;
    md.push('## Security preflight (before any timing, every trial)', '');
    md.push('| Trial | Config | valid | missing | tampered | revoked | wrong aud | Passed |');
    md.push('|---|---|---|---|---|---|---|---|');
    for (const p of preflights) {
      const a = p.answers;
      md.push(`| ${p.trial} | ${p.config} | ${a.valid} | ${a.missing} | ${a.tampered ?? '—'} | ${a.revoked ?? '—'} | ${a.wrongAudience ?? '—'} | ${p.passed ? 'yes' : `**NO** (${p.mismatches.join(', ')})`} |`);
    }
    md.push('', '`jwt-stateless` answering **200** to a revoked token is its expected, disclosed behaviour: it has no server-side revocation.', '');

    md.push('## Comparison 2 — protected requests over HTTP (closed loop, keep-alive)', '');
    md.push('| Config | Comparable | Concurrency | Trials | Throughput req/s (range) | p50 ms (range) | p95 ms | p99 ms | CV of throughput | non-200 |');
    md.push('|---|---|---|---|---|---|---|---|---|---|');
    const configs = [...new Set(rows.map((r) => r.config))];
    const levels = [...new Set(rows.map((r) => r.concurrency))].sort((a, b) => a - b);
    for (const c of levels) {
      for (const config of ['ninsho-opaque', 'ninsho-paseto', 'jwt-redis', 'jwt-stateless', 'no-auth'].filter((x) => configs.includes(x))) {
        const rs = rows.filter((r) => r.config === config && r.concurrency === c);
        if (rs.length === 0) continue;
        const rps = acrossTrials(rs.map((r) => r.throughputRps));
        const p50 = acrossTrials(rs.map((r) => r.p50Ms));
        const p95 = acrossTrials(rs.map((r) => r.p95Ms));
        const p99 = acrossTrials(rs.map((r) => r.p99Ms));
        const nonOk = rs.reduce((s, r) => s + r.nonOk, 0);
        const comparable = ['ninsho-opaque', 'ninsho-paseto', 'jwt-redis'].includes(config);
        out.http.push({ config, comparable, concurrency: c, throughputRps: rps, p50, p95, p99, nonOk, requestsPerTrial: rs.map((r) => r.requests) });
        md.push(`| ${config} | ${comparable ? 'yes' : 'reference'} | ${c} | ${rps.n} | ${f(rps.median, 0)} (${range(rps, 0)}) | ${f(p50.median, 2)} (${range(p50, 2)}) | ${f(p95.median, 2)} | ${f(p99.median, 2)} | ${f(rps.cvPercent, 1)}% | ${nonOk} |`);
      }
    }
    md.push('', '### What each configuration checks per request', '');
    for (const [k, v] of Object.entries(checks)) md.push(`- **${k}** — ${v}`);
    md.push('');
  }

  writeFileSync(path.join(runDir, 'summary.json'), JSON.stringify(out, null, 2));
  writeFileSync(path.join(runDir, 'summary.md'), md.join('\n'));
  return out;
}

if (process.argv[1]?.endsWith('summarize.mjs')) {
  if (!process.argv[2]) { console.error('usage: node summarize.mjs <run-dir>'); process.exit(2); }
  summarize(path.resolve(process.argv[2]));
  console.log(`wrote ${path.join(process.argv[2], 'summary.md')}`);
}
